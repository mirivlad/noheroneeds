#!/usr/bin/env python3
"""Berries (an item icon, 32 px): drawn by hand as rows of letters, in the
LPC plants' reds and greens. Usage: tools/art/generated/berries/make.py"""
from pathlib import Path
from PIL import Image

PAL = {"k": (40, 22, 26), "r": (196, 40, 52), "R": (236, 84, 84), "h": (255, 190, 180), "d": (128, 24, 40),
       "g": (84, 150, 60), "G": (44, 96, 44), "b": (96, 64, 40)}
ROWS = """
................................
................................
................................
................................
..................G.............
.................GgG............
................GgggGG..........
...............GgggggGG.........
...........b..GGgGGGgG..........
..........b...G.GG.GG...........
.........b......b...............
........b......b................
.......b.....kkkk...............
......b.....kRRhRk..............
.....b.....kRRRRhRk.............
....kkkk...kRrRRRRk.kkkk........
...kRRhRk..kdrrRRrkkRRhRk.......
..kRRRRhRk..kdrrrrkRRRRhRk......
..kRrRRRRk...kkkkkRrRRRRRk......
..kdrrRRrk....kkkkkdrrRRrk......
..kddrrrrk...kRRhRkkdrrrrk......
...kdddrk...kRRRRhRkkddrk.......
....kkkk....kRrRRRRk.kkk........
............kdrrRRrk............
............kddrrrrk............
.............kdddrk.............
..............kkkk..............
................................
................................
................................
................................
................................
"""
rows = [r for r in ROWS.strip("\n").split("\n")]
img = Image.new("RGBA", (32, 32))
for y, r in enumerate(rows):
    for x, c in enumerate(r):
        if c in PAL:
            img.putpixel((x, y), PAL[c] + (255,))
out = Path(__file__).with_name("berries.png")
img.save(out)
print(out)
